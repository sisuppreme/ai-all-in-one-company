#!/usr/bin/env python3
"""Generate SKILLS_INDEX.md from the skills themselves (MASTER_BRIEF.md §5.3).

The index is generated by this script from skill metadata — never hand-maintained.
Re-run after any skill is added, removed, or edited:

    python3 scripts/build-index.py

Sources parsed:
- skills/<department>/<skill>/SKILL.md  (Metadata + When-to-use sections, Gates section)
- docs/PROJECT_ANATOMY.md               ("Skills that serve it" lines, inverted)

Definitions:
- Token estimate (Size field): tokens = ceil(characters / 4), counted over the
  raw SKILL.md file text. It is a budgeting estimate, not a tokenizer count.
- "Load with" is DERIVED FROM METADATA: the union of the skill's declared
  Depends-on and Feeds-into neighbours (annotations stripped), in declared order.
- Keywords are derived deterministically: skill-name tokens first, then content
  words from the skill's own Use-when line (lowercased, stopwords removed,
  deduplicated, max 8). No terms are invented.
- skills/detection/ is EXCLUDED: detection parameters are indexed inside their
  own PARAMETERS.md files, not here.
"""
import math
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = ROOT / "skills"
ANATOMY = ROOT / "docs" / "PROJECT_ANATOMY.md"
OUT = ROOT / "SKILLS_INDEX.md"

# Folder -> D-number, per the §5.1 target layout, in D1..D18 order.
DEPARTMENTS = [
    ("product-requirements", "D1"),
    ("architecture", "D2"),
    ("frontend", "D3"),
    ("backend", "D4"),
    ("database", "D5"),
    ("devops-deployment", "D6"),
    ("security", "D7"),
    ("qa-testing", "D8"),
    ("seo-content", "D9"),
    ("project-memory", "D10"),
    ("integrations-payments", "D11"),
    ("analytics-observability", "D12"),
    ("accessibility-i18n", "D13"),
    ("legal-privacy", "D14"),
    ("developer-experience", "D15"),
    ("cloning-replication", "D16"),
    ("ai-features", "D17"),
    ("customer-experience", "D18"),
]

STOPWORDS = {
    "a", "an", "the", "and", "or", "of", "to", "in", "on", "for", "with",
    "without", "when", "any", "its", "it", "is", "are", "be", "by", "at",
    "from", "as", "that", "this", "these", "those", "into", "over", "under",
    "per", "via", "not", "no", "nor", "but", "if", "so", "such", "than",
    "then", "they", "them", "their", "we", "you", "your", "our", "one",
    "all", "each", "every", "must", "should", "will", "can", "may", "do",
    "does", "done", "being", "been", "has", "have", "had", "was", "were",
    "what", "which", "who", "how", "about", "between", "through", "during",
    "before", "after", "only", "own", "same", "too", "very", "just",
}


def section(text, heading, next_headings):
    """Return the text between `heading` and the first of next_headings."""
    start = text.find(heading)
    if start == -1:
        return ""
    start += len(heading)
    end = len(text)
    for h in next_headings:
        i = text.find(h, start)
        if i != -1:
            end = min(end, i)
    return text[start:end]


def meta_field(meta, label):
    m = re.search(rf"^- \*\*{re.escape(label)}:\*\*\s*(.+)$", meta, re.M)
    return m.group(1).strip() if m else ""


def parse_names(value):
    """Extract bare skill names from a Depends-on / Feeds-into value.

    Splits on commas outside parentheses, drops parenthetical annotations
    and trailing em-dash notes, and drops 'none'.
    """
    parts, depth, cur = [], 0, ""
    for ch in value:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth = max(0, depth - 1)
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    names = []
    for p in parts:
        p = re.sub(r"\([^)]*\)", "", p)
        p = p.split("—")[0].strip().strip("`").rstrip(".")
        if p and p.lower() != "none" and p not in names:
            names.append(p)
    return names


def derive_keywords(name, use_when):
    seen, out = set(), []
    candidates = name.split("-") + re.findall(r"[a-z0-9][a-z0-9\-']*", use_when.lower())
    for w in candidates:
        w = re.sub(r"'s$", "", w).strip("-'")
        if len(w) < 2 or w in STOPWORDS or w in seen:
            continue
        seen.add(w)
        out.append(w)
        if len(out) == 8:
            break
    return out


def parse_anatomy():
    """Invert PROJECT_ANATOMY.md: skill name -> [element names, doc order]."""
    skill_to_elements = {}
    current = None
    for line in ANATOMY.read_text(encoding="utf-8").splitlines():
        h = re.match(r"^## (.+)$", line)
        if h:
            current = h.group(1).strip()
        m = re.match(r"^- \*\*Skills that serve it:\*\*\s*(.+)$", line)
        if m and current:
            for raw in m.group(1).split(","):
                name = raw.strip().strip("`").rstrip(".")
                if name:
                    elements = skill_to_elements.setdefault(name, [])
                    if current not in elements:
                        elements.append(current)
    return skill_to_elements


def parse_skill(skill_md, folder, dnum):
    text = skill_md.read_text(encoding="utf-8")
    h1 = re.search(r"^# (.+)$", text, re.M)
    name = h1.group(1).strip() if h1 else skill_md.parent.name
    meta = section(text, "## Metadata", ["## When to use"])
    when = section(text, "## When to use / Do NOT use", ["## Rules"])
    gates_sec = section(text, "## Gates", ["## Anti-patterns"])

    owner = meta_field(meta, "Owner department")
    owner_d = re.match(r"(D\d+)\b", owner)
    if owner_d and owner_d.group(1) != dnum:
        print(f"warning: {name}: owner department {owner_d.group(1)} != folder map {dnum}",
              file=sys.stderr)
    dept_name = re.sub(r"\(.*?\)\s*$", "", re.sub(r"^D\d+\s+", "", owner)).strip()

    use_m = re.search(r"^- \*\*Use when:\*\*\s*(.+)$", when, re.M)
    dont_m = re.search(r"^- \*\*Do NOT use when:\*\*\s*(.+)$", when, re.M)
    depends_raw = meta_field(meta, "Depends on")
    feeds_raw = meta_field(meta, "Feeds into")
    version = meta_field(meta, "Skill version")
    gates = []
    for g in re.findall(r"\*\*(G-[A-Z]{2}-\d{3})\b", gates_sec):
        if g not in gates:
            gates.append(g)
    load_with = parse_names(depends_raw) + [
        n for n in parse_names(feeds_raw) if n not in parse_names(depends_raw)
    ]
    return {
        "name": name,
        "dept": dnum,
        "dept_name": dept_name,
        "use_when": use_m.group(1).strip() if use_m else "",
        "do_not_use": dont_m.group(1).strip() if dont_m else "",
        "depends_on": depends_raw,
        "feeds_into": feeds_raw,
        "load_with": load_with,
        "path": skill_md.relative_to(ROOT).as_posix(),
        "gates": gates,
        "lines": len(text.splitlines()),
        "tokens": math.ceil(len(text) / 4),
        "keywords": derive_keywords(name, use_m.group(1) if use_m else ""),
        "status": "Draft" if version.startswith("0.") else "Stable",
    }


def main():
    anatomy = parse_anatomy()
    by_dept = []
    all_skills = []
    for folder, dnum in DEPARTMENTS:
        dept_dir = SKILLS_DIR / folder
        skills = [
            parse_skill(p, folder, dnum)
            for p in sorted(dept_dir.glob("*/SKILL.md"))
        ]
        skills.sort(key=lambda s: s["name"])
        by_dept.append((dnum, folder, skills))
        all_skills.extend(skills)

    problems = []
    for s in all_skills:
        if not s["gates"]:
            problems.append(f"{s['name']}: no gates defined in Gates section")
        if not s["use_when"] or not s["do_not_use"]:
            problems.append(f"{s['name']}: missing Use when / Do NOT use when line")
        if s["name"] not in anatomy:
            print(f"warning: {s['name']}: no anatomy element serves it", file=sys.stderr)
        if not s["load_with"]:
            print(f"warning: {s['name']}: no declared links (Depends on / Feeds into both empty)",
                  file=sys.stderr)
    known = {s["name"] for s in all_skills}
    for name in sorted(set(anatomy) - known):
        print(f"warning: anatomy names unknown skill '{name}'", file=sys.stderr)
    if problems:
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        return 1

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out = []
    out.append("# SKILLS_INDEX.md — the skill catalog")
    out.append("")
    out.append(
        "Generated by `scripts/build-index.py` from the skills' own metadata — "
        "**do not hand-edit**; edit the skill and re-run the script."
    )
    out.append("")
    out.append(
        "**Repo-first use:** read `BOOTSTRAP.md` first. Then scan this index by "
        "department section and Keywords to identify the skills a task needs — do not "
        "read every entry, and do not load a skill until the index says it fits. "
        "Match task type to a playbook first; else match task keywords to the Keywords "
        "field; if nothing matches, load the core bundle and ask the user (§5.2)."
    )
    out.append("")
    out.append(
        "**Excluded:** `skills/detection/` — detection parameters are indexed inside "
        "their own `PARAMETERS.md` files, not in this catalog."
    )
    out.append("")
    out.append("**Fields** (per §5.3): *Depends on* = must load first (prerequisite); "
               "*Feeds into* = skills that consume this one's output; "
               "*Load with (derived from metadata)* = the skill's declared Depends-on ∪ "
               "Feeds-into neighbours, commonly used together (optional); "
               "*Size* = SKILL.md line count / token estimate, where tokens = "
               "ceil(characters ÷ 4) over the raw file — budget before loading; "
               "*Keywords* are derived from the skill name and its own Use-when line; "
               "*Anatomy element* = the `docs/PROJECT_ANATOMY.md` element(s) the skill serves.")
    out.append("")
    out.append("## Departments")
    out.append("")
    for dnum, folder, skills in by_dept:
        dept_name = skills[0]["dept_name"] if skills else folder
        out.append(f"- **{dnum} — {dept_name}** ({len(skills)} skills) — `skills/{folder}/`")
    out.append("")
    for dnum, folder, skills in by_dept:
        dept_name = skills[0]["dept_name"] if skills else folder
        out.append(f"## {dnum} — {dept_name}")
        out.append("")
        for s in skills:
            out.append(f"### {s['name']}")
            out.append("")
            out.append(f"- **Department:** {s['dept']}")
            out.append(f"- **Use when:** {s['use_when']}")
            load = ", ".join(f"`{n}`" for n in s["load_with"]) or "—"
            out.append(f"- **Load with (derived from metadata):** {load}")
            out.append(f"- **Depends on:** {s['depends_on'] or '—'}")
            out.append(f"- **Feeds into:** {s['feeds_into'] or '—'}")
            out.append(f"- **Do NOT use when:** {s['do_not_use']}")
            out.append(f"- **Path:** `{s['path']}`")
            out.append(f"- **Gates:** {', '.join(s['gates'])}")
            out.append(f"- **Size:** {s['lines']} lines / ~{s['tokens']} tokens")
            out.append(f"- **Keywords:** {', '.join(s['keywords'])}")
            out.append(f"- **Status:** {s['status']}")
            elements = anatomy.get(s["name"], [])
            out.append(f"- **Anatomy element:** {'; '.join(elements) if elements else '—'}")
            out.append("")
    out.append("---")
    out.append("")
    out.append(f"Generated {now} by `scripts/build-index.py` · {len(all_skills)} skills · "
               f"{len(DEPARTMENTS)} departments.")
    out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUT.name}: {len(all_skills)} skills indexed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
