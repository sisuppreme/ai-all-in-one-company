#!/usr/bin/env python3
"""Generate the bundles/ files from the skills (MASTER_BRIEF.md §5.8).

Bundles are generated by this script — never hand-edited. Re-run after any
skill or playbook change:

    python3 scripts/build-bundles.py

Outputs (33 files in bundles/, plus one extra part file for each department
split at rung 3 — see the rung-3 note below):
- core.md            BOOTSTRAP + condensed index + the four always-on skills.
                     HARD CAP: under 10,000 tokens.
- <department>.md    one per department (18): every skill of the department in
                     bundle form (see below). Cap: 30,000 tokens. A department
                     split at rung 3 also produces <department>-2.md.
- <playbook>.md      one per playbook (13): the playbook file + the skills its
                     "Skills to load" section names. Cap: 30,000 tokens.
- ALL_SKILLS.md      every SKILL.md in department order. Reference/download
                     artifact only — no cap; never loaded whole.

Definitions:
- Token measure: tokens = ceil(characters / 4), counted over the raw file
  text — the same definition as scripts/build-index.py. It is a budgeting
  estimate, not a tokenizer count. Caps in characters: core < 10,000 tokens
  means <= 39,996 characters; 30,000 tokens means <= 120,000 characters.
- Skill line cap: 400 lines per SKILL.md (§5.4). The build fails if a skill
  this script references is missing or over the line cap (§5.8 generation
  rule).

Condensation ladders (deterministic; the cap always wins, and each bundle's
header records which rung/stage was used and which skills are condensed):
- core.md stages: (1) always-on skills in full + full condensed index;
  (2) always-on skills condensed to Rules + Recall anchors + Checklist,
  index use-when lines truncated at a word boundary to the largest uniform
  budget that fits (only if that budget is >= 40 characters);
  (3) always-on skills as condensed checklists (Checklist + Recall anchors,
  the §5.8 fallback wording) + truncated index as in (2);
  (4) always-on condensed as in (2) + name/path-only index lines;
  (5) always-on condensed as in (3) + name/path-only index lines.
  Truncated use-when lines are marked with an ellipsis; the full text lives
  in SKILLS_INDEX.md.
- Playbook rungs: (1) the brief's §5.6 key skills in full, every other named
  skill condensed to Rules + Checklist; (2) all named skills condensed to
  Rules + Checklist; (3) key skills condensed, the rest as one-line pointers
  (name + use-when + path); (4) all named skills as pointers. The four
  always-on core skills are never repeated in a playbook bundle — they ship
  in core.md, which every playbook loads first (a pointer notes this).
  Playbooks added by DECISIONS D-007 (booking-scheduling, online-learning-lms)
  have no §5.6 key-skill list in the brief; both were assigned one in the
  Phase 6 defect loop (DR-04): with no key skills a bundle falls to
  pointers only, and the online-learning-lms bundle carried no skill
  content at all.
- Gate criteria digest (DR-04, Phase 6 defect loop): every playbook bundle,
  at every rung, ends with a digest of every gate the playbook cites that
  is defined in a skill — the gate's ID and name, its Check criterion
  condensed to its first sentence(s) where long (the same condensation
  as department rung 2), and its Pass criterion complete and exact,
  grouped under the owning skill. The digest is never condensed away by
  the rungs: it is what makes the playbook bundle the default complete
  load for a walk, so a single agent following the prescribed route
  (BOOTSTRAP.md step 3, staged loading — DR-15) can see what every
  cited gate checks without loading the full skills.
- Department bundle form (Phase 5 executor decision): full text cannot meet
  the §5.8 cap for the larger departments (measured: 12 of 18 over 30,000
  tokens at full text), so department bundles ship each skill in "bundle
  form", generated deterministically from the SKILL.md: Metadata, When to
  use / Do NOT use, Rules, Gates, Recall anchors, and Checklist in full; the
  BAN list with every entry's ID, pattern, Defeats, Instead, and Severity,
  omitting only the "Bad:" narrative example; the Examples and Anti-patterns
  sections are not copied. Each department bundle's header states this and
  points at the source skills (`skills/<department>/<skill>/SKILL.md`), and
  the full text of every skill remains in ALL_SKILLS.md. Source SKILL.md
  files are never edited by this script.
- Department rung 2 (applied only to a department whose bundle-form bundle
  still exceeds the cap): in addition to the bundle-form rules, each skill's
  Recall anchors section and Metadata Sources line are omitted, and each
  gate is condensed to its ID, the rule IDs it verifies, its Check reduced
  to the first sentence (two sentences when the first is a fragment or a
  list intro), its Pass criterion complete and exact, and its Fail action;
  a "[check condensed — full procedure in the source skill]" marker is
  appended once per skill Gates section. The rung-2 bundle header states
  plainly that the bundle is rung-2 condensed, what was condensed, and
  points at the source skills and ALL_SKILLS.md.
- Department rung 3 (applied only to a department whose rung-2 bundle still
  exceeds the cap): in addition to the rung-2 rules, each skill's Checklist
  section is omitted — every checklist item restates a rule that remains in
  full in the bundle, and the rung-3 header states that the checklists live
  in the source skills. Rules and BAN substance are never condensed at any
  rung. If a department still exceeds its cap after rung 3, its bundle is
  split at a skill boundary into <department>.md and <department>-2.md,
  each in rung-3 form: skills are ordered by use (how often the rest of the
  catalog names them in Depends on / Feeds into metadata, ties broken by
  name) and part 1 is filled first, so the more-used skills ship in part 1;
  each part's header names the other part and lists which skills each part
  holds. If a split part still exceeds its cap the build reports FAIL for
  it (exit non-zero) and the executor decides.

Byte stability: a bundle whose regenerated content differs from the file on
disk only in the generation stamp is left untouched, so re-running this
script never rewrites an unchanged bundle.

Exit codes: 0 = every cap satisfied; 1 = a referenced skill is missing/over
the line cap (nothing is written), or at least one bundle exceeds its cap
(all bundles are still written and the size table shows the failures).
"""
