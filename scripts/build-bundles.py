def tokens(text):
    return math.ceil(len(text) / 4)


def section(text, heading):
    """Return `heading` plus its body, up to the next known section heading."""
    start = text.find(heading)
    if start == -1:
        return ""
    end = len(text)
    for h in SECTION_HEADS:
        if h == heading:
            continue
        i = text.find(h, start + len(heading))
        if i != -1:
            end = min(end, i)
    return text[start:end].rstrip()


def strip_ban_bad(ban_section_text):
    """Remove the "Bad:" narrative example from each BAN entry in the section.

    BAN entries are single-line bullets in the validated format
    "- **BAN-<CODE>-NNN — <title>.** Banned: <pattern>. Defeats: <DET ref>.
    Bad: <narrative>. Instead: <replacement>. Severity: <level>." — exactly
    one " Bad: " and one following " Instead: " per entry (verified across
    all 227 skills). Everything except the narrative is kept verbatim.
    """
    lines = []
    for line in ban_section_text.splitlines():
        if line.lstrip().startswith("- **BAN-"):
            line = re.sub(r" Bad: .*?(?= Instead:)", "", line)
        lines.append(line)
    return "\n".join(lines)


def strip_sources(metadata_section_text):
    """Remove the "- **Sources:**" line from a Metadata section (rung 2)."""
    return "\n".join(
        line for line in metadata_section_text.splitlines()
        if not line.startswith("- **Sources:**"))


def split_sentences(text):
    """Split prose into sentences, deterministically.

    A sentence ends at [.!?] followed by a space and an uppercase letter, a
    digit, or an opening quote/backtick/paren. Periods inside backtick code
    spans and after known abbreviations (e.g., i.e., etc.) do not split;
    decimals never split because no space follows the point.
    """
    spans = []

    def mask(match):
        spans.append(match.group(0))
        return f"\x00{len(spans) - 1}\x00"

    masked = re.sub(r"`[^`]*`", mask, text)
    parts = []
    start = 0
    for m in re.finditer(r"[.!?]", masked):
        i = m.start()
        rest = masked[i + 1:]
        if not rest.startswith(" "):
            continue
        nxt = rest.lstrip()
        if not nxt:
            break
        if not (nxt[0].isupper() or nxt[0].isdigit() or nxt[0] in '"\u201c(\u2018'):
            continue
        if masked[i] == ".":
            words = masked[:i].rstrip().split()
            if words and (words[-1].lower() + ".") in ABBREVIATIONS:
                continue
        parts.append(masked[start:i + 1])
        start = i + 1
    parts.append(masked[start:])
    out = []
    for p in parts:
        p = re.sub(r"\x00(\d+)\x00", lambda mm: spans[int(mm.group(1))], p).strip()
        if p:
            out.append(p)
    return out


def condense_check(check_text):
    """Reduce a gate Check to its first sentence (rung 2).

    A single-sentence check is kept whole. When the first sentence is a
    fragment or a list intro — it ends with a colon, ends with a bare item
    number ("...: 1."), or runs to fewer than four words — the first two
    sentences are kept. Returns (text, shortened).
    """
    text = check_text.strip()
    sentences = split_sentences(text)
    if len(sentences) <= 1:
        return text, False
    first = sentences[0]
    fragment = (first.endswith(":")
                or re.search(r"\b\d+\.$", first) is not None
                or len(first.split()) < 4)
    if fragment:
        kept = " ".join(sentences[:2])
        return kept, kept != text
    return first, first != text


def condense_gate_bullet(line):
    """Condense one gate bullet (rung 2); unparseable bullets pass through.

    Keeps the bold head (gate ID + name), the Verifies list, the Check
    marker ("Check:", "Check (automated):", ...) with the condensed check,
    the Pass criterion verbatim, and the Fail action verbatim. The trailing
    "Recorded in: ..." boilerplate is dropped. Returns (line, shortened)
    where shortened says whether the Check text itself was reduced.
    """
    vi = line.find(" Verifies: ")
    if vi == -1:
        return line, False
    head, rest = line[:vi], line[vi + len(" Verifies: "):]
    m = CHECK_MARKER_RE.search(rest)
    if not m:
        return line, False
    verifies = rest[:m.start()].rstrip()
    marker = m.group(0).strip()
    rest = rest[m.end():]
    pi = rest.find(" Pass: ")
    if pi == -1:
        return line, False
    check, rest = rest[:pi], rest[pi + len(" Pass: "):]
    fi = rest.find(" Fail: ")
    if fi == -1:
        return line, False
    pass_text, rest = rest[:fi].strip(), rest[fi + len(" Fail: "):]
    ri = rest.find(" Recorded in: ")
    fail_text = (rest[:ri] if ri != -1 else rest).strip()
    new_check, shortened = condense_check(check)
    return (f"{head} Verifies: {verifies} {marker} {new_check} "
            f"Pass: {pass_text} Fail: {fail_text}"), shortened


def condense_gates_section(gates_section_text):
    """Condense every gate bullet in a Gates section (rung 2).

    Non-bullet lines (section heading, notes) pass through verbatim. The
    condensed-check marker is appended once, at the end of the section.
    """
    out = []
    for line in gates_section_text.splitlines():
        if line.lstrip().startswith("- **G-"):
            line, _shortened = condense_gate_bullet(line)
        out.append(line)
    out.append(CHECK_CONDENSED_MARKER)
    return "\n".join(out)


def use_when(text):
    when = section(text, "## When to use / Do NOT use")
    m = re.search(r"^- \*\*Use when:\*\*\s*(.+)$", when, re.M)
    return m.group(1).strip() if m else ""


def truncate_words(text, budget):
    """Truncate to at most `budget` chars at a word boundary, with an ellipsis."""
    if len(text) <= budget:
        return text
    if budget <= 1:
        return "…" if budget == 1 else ""
    cut = text[:budget - 1]
    if " " in cut:
        cut = cut[:cut.rfind(" ")]
    return cut.rstrip(" ,;:") + "…"


class Skill:
    def __init__(self, path, folder, dnum):
        self.path = path
        self.folder = folder
        self.dnum = dnum
        self.name = path.parent.name
        self.rel = path.relative_to(ROOT).as_posix()
        self.text = path.read_text(encoding="utf-8")
        self.lines = len(self.text.splitlines())
        self.use_when = use_when(self.text)

    def full(self):
        return f"<!-- generated from {self.rel} -->\n\n{self.text.rstrip()}"

    def bundle_form(self):
        """This skill as it ships in its department bundle (bundle-form rule).

        Metadata, When to use / Do NOT use, Rules, BAN list, Gates, Recall
        anchors, and Checklist in full; BAN entries keep ID, pattern,
        Defeats, Instead, and Severity with only the "Bad:" narrative
        omitted; the Examples and Anti-patterns sections are not copied.
        A pure function of the SKILL.md text — deterministic.
        """
        title = self.text[:self.text.find("## Metadata")].rstrip()
        parts = [f"<!-- generated from {self.rel} (bundle form) -->",
                 "",
                 title,
                 ""]
        for h in BUNDLE_FORM_HEADS:
            sec = section(self.text, h)
            if not sec:
                continue
            if h == "## BAN list":
                sec = strip_ban_bad(sec)
            parts += [sec, ""]
        return "\n".join(parts).rstrip()

    def bundle_form_rung2(self):
        """Bundle form plus the rung-2 condensations, for departments whose
        bundle-form bundle still exceeds the cap: no Recall anchors section,
        no Metadata Sources line, and every gate's Check reduced to its
        first sentence (Pass and Fail kept complete). A pure function of
        the SKILL.md text — deterministic.
        """
        title = self.text[:self.text.find("## Metadata")].rstrip()
        parts = [f"<!-- generated from {self.rel} (bundle form, rung 2) -->",
                 "",
                 title,
                 ""]
        for h in RUNG2_HEADS:
            sec = section(self.text, h)
            if not sec:
                continue
            if h == "## BAN list":
                sec = strip_ban_bad(sec)
            elif h == "## Metadata":
                sec = strip_sources(sec)
            elif h == "## Gates":
                sec = condense_gates_section(sec)
            parts += [sec, ""]
        return "\n".join(parts).rstrip()

    def bundle_form_rung3(self):
        """Rung 2 plus the rung-3 condensation, for departments whose
        rung-2 bundle still exceeds the cap: the Checklist section is also
        omitted (every checklist item restates a rule kept in full here;
        the checklists live in the source skills). Rules and BAN substance
        are never condensed. A pure function of the SKILL.md text.
        """
        title = self.text[:self.text.find("## Metadata")].rstrip()
        parts = [f"<!-- generated from {self.rel} (bundle form, rung 3) -->",
                 "",
                 title,
                 ""]
        for h in RUNG3_HEADS:
            sec = section(self.text, h)
            if not sec:
                continue
            if h == "## BAN list":
                sec = strip_ban_bad(sec)
            elif h == "## Metadata":
                sec = strip_sources(sec)
            elif h == "## Gates":
                sec = condense_gates_section(sec)
            parts += [sec, ""]
        return "\n".join(parts).rstrip()

    def condensed(self, heads, label):
        parts = [f"<!-- generated from {self.rel} (condensed: {label}) -->",
                 "",
                 f"# {self.name}",
                 "",
                 f"*Condensed for this bundle — {label} only. Full skill: "
                 f"`{self.rel}` (also in `bundles/{self.folder}.md`).*"]
        for h in heads:
            sec = section(self.text, h)
            if sec:
                parts += ["", sec]
        return "\n".join(parts)

    def pointer(self):
        return (f"<!-- generated from {self.rel} (pointer) -->\n"
                f"- **{self.name}** — {self.use_when} (`{self.rel}`; "
                f"full text in `bundles/{self.folder}.md`)")


def load_catalog():
    catalog = {}
    ordered = []  # (dnum, folder, [Skill]) in D1..D18 order, skills by name
    for folder, dnum in DEPARTMENTS:
        skills = [Skill(p, folder, dnum)
                  for p in sorted((SKILLS_DIR / folder).glob("*/SKILL.md"))]
        skills.sort(key=lambda s: s.name)
        ordered.append((dnum, folder, skills))
        for s in skills:
            catalog[s.name] = s
    return catalog, ordered


def parse_playbook_skills(playbook_text, catalog):
    """Extract skill names from the playbook's 'Skills to load' table.

    The skills column is the one whose header mentions 'skill'; entries are
    split on ';' (department groups) and ','; parenthetical annotations and
    em-dash notes are stripped. A leftover fragment shaped like a skill name
    (single lowercase hyphenated token) that is not in the catalog is a
    missing reference and is returned in `missing`.
    """
    if "## Skills to load" not in playbook_text:
        return [], ["<no 'Skills to load' section>"]
    sec = playbook_text.split("## Skills to load", 1)[1].split("\n## ", 1)[0]
    rows = [l for l in sec.splitlines() if l.strip().startswith("|")]
    if not rows:
        return [], ["<no table in 'Skills to load' section>"]
    header = [c.strip().lower() for c in rows[0].strip().strip("|").split("|")]
    col = next((i for i, h in enumerate(header) if "skill" in h),
               1 if len(header) > 2 else 0)
    names, missing = [], []
    for line in rows[1:]:
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) <= col:
            continue
        cell = cells[col]
        if not cell or set(cell) <= set("-: "):
            continue
        for group in cell.split(";"):
            group = re.sub(r"\([^)]*\)", "", group)
            for tok in group.split(","):
                tok = tok.split("—")[0].strip().strip("`").rstrip(".")
                if not tok:
                    continue
                if tok in catalog:
                    if tok not in names:
                        names.append(tok)
                elif re.fullmatch(r"[a-z0-9][a-z0-9\-]*", tok):
                    if tok not in missing:
                        missing.append(tok)
    return names, missing


def gen_stamp():
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


GATE_CITATION_RE = re.compile(r"\bG-[A-Z]{2}-\d{2,3}\b")


def gate_index(catalog):
    """Gate ID -> (owning Skill, gate bullet line), from every skill's
    ## Gates section. A bullet that does not parse is not indexed."""
    index = {}
    for s in catalog.values():
        for raw in section(s.text, "## Gates").splitlines():
            line = raw.strip()
            m = re.match(r"- \*\*(G-[A-Z]{2}-\d{2,3})\b", line)
            if m and m.group(1) not in index:
                index[m.group(1)] = (s, line)
    return index


def digest_entry(line):
    """One gate bullet as a digest entry: ID + name, the Check condensed
    to its first sentence(s) where long, the Pass criterion complete.
    None when the bullet carries no Check marker or no Pass criterion."""
    start = line.index("**") + 2
    end = line.index("**", start)
    head = line[start:end].rstrip(".")
    if " — " in head:
        gid, _, name = head.partition(" — ")
    else:
        gid, _, name = head.partition(" ")
    rest = line[end + 2:]
    m = CHECK_MARKER_RE.search(rest)
    if not m:
        return None
    after = rest[m.end():]
    pi = after.find(" Pass: ")
    if pi == -1:
        return None
    check, rest2 = after[:pi], after[pi + len(" Pass: "):]
    ends = [i for i in (rest2.find(" Fail: "),
                        rest2.find(" Recorded in: ")) if i != -1]
    pass_text = (rest2[:min(ends)] if ends else rest2).strip()
    check_text, _shortened = condense_check(check)
    return f"- **{gid} — {name}.** Check: {check_text} Pass: {pass_text}"


def gate_digest(pb_text, work_order, catalog, index):
    """The gate criteria digest for one playbook bundle (DR-04): every
    gate the playbook cites that resolves to a skill-defined gate, grouped
    under its owning skill — the playbook's routed skills first, in
    playbook order, then any other owning skill in catalog order."""
    cited = list(dict.fromkeys(GATE_CITATION_RE.findall(pb_text)))
    by_skill = {}
    for gid in cited:
        if gid in index:
            by_skill.setdefault(index[gid][0].name, []).append(gid)
    if not by_skill:
        return ""
    order = [n for n in work_order if n in by_skill]
    order += [n for n in catalog if n in by_skill and n not in order]
    parts = [
        "## Gate criteria digest — every gate this playbook cites",
        "",
        "Generated from the owning skills: each cited gate's Check "
        "criterion, condensed to its first sentence(s) where long, and "
        "its Pass criterion complete and exact. Fail actions and full "
        "procedures live in the owning skill and in the department "
        "bundles. This digest ships at every rung — it is what makes "
        "this bundle the default complete load for the walk "
        "(BOOTSTRAP.md step 3).",
        "",
    ]
    for n in order:
        s = catalog[n]
        parts += [f"### {n} (`{s.rel}`)", ""]
        for gid in by_skill[n]:
            entry = digest_entry(index[gid][1])
            if entry:
                parts.append(entry)
        parts.append("")
    return "\n".join(parts).rstrip()


def build_core(catalog, ordered):
    bootstrap = BOOTSTRAP.read_text(encoding="utf-8").rstrip()
    always = [catalog[n] for n in ALWAYS_ON]
    all_skills = [s for _, _, ss in ordered for s in ss]
    limit_chars = CORE_TOKEN_CAP * 4 - 4  # strictly under the token cap

    def header(stage_note):
        return "\n".join([
            "# Bundle: core.md — BOOTSTRAP + condensed index + always-on skills",
            "",
            f"<!-- generated by scripts/build-bundles.py on {gen_stamp()} — "
            "do not hand-edit; regenerate after any skill change -->",
            "",
            "Every agent loads this bundle first. It contains the repo-first "
            "protocol (BOOTSTRAP.md), a condensed index of every skill "
            "(name + use-when + path, one line per skill), and the four "
            "always-on skills: `project-templates`, `progress-tracking` "
            "(D10), `secrets-management` (D7), `qa-gates` (D8).",
            "",
            stage_note,
            "",
            "---",
            "",
        ])

    def index_lines(budget):
        lines = ["## Condensed index — all skills (name + use-when + path)", ""]
        for s in all_skills:
            uw = s.use_when if budget is None else truncate_words(s.use_when, budget)
            lines.append(f"- **{s.name}** — {uw} (`{s.rel}`)")
        return "\n".join(lines)

    def assemble(always_block, budget):
        return "\n".join([
            header(STAGE_NOTE),
            bootstrap,
            "",
            "---",
            "",
            index_lines(budget),
            "",
            "---",
            "",
            "## Always-on skills",
            "",
            always_block,
            "",
        ])

    def budget_for(always_block):
        base = assemble(always_block, 0)
        room = limit_chars - len(base) - 2 * len(all_skills)  # ellipsis slack
        return room // len(all_skills) if all_skills else 0

    full_block = "\n\n".join(s.full() for s in always)
    rca_block = "\n\n".join(
        s.condensed(["## Rules", "## Recall anchors", "## Checklist"],
                    "Rules + Recall anchors + Checklist") for s in always)
    ca_block = "\n\n".join(
        s.condensed(["## Checklist", "## Recall anchors"],
                    "Checklist + Recall anchors") for s in always)

    # Stage 1: always-on in full, full index.
    STAGE_NOTE = ("Assembly: stage 1 — always-on skills in full; index "
                  "use-when lines in full.")
    out = assemble(full_block, None)
    if tokens(out) < CORE_TOKEN_CAP:
        return out
    # Stage 2: always-on Rules+anchors+checklist, truncated index (budget >= 40).
    STAGE_NOTE = ("Assembly: stage 2 — always-on skills condensed to Rules + "
                  "Recall anchors + Checklist (pointers to the full skills "
                  "included); index use-when lines truncated at a word "
                  "boundary — full text in `SKILLS_INDEX.md`.")
    budget = budget_for(rca_block)
    if budget >= 40:
        out = assemble(rca_block, budget)
        if tokens(out) < CORE_TOKEN_CAP:
            return out
    # Stage 3: always-on as condensed checklists (§5.8 fallback), truncated index.
    STAGE_NOTE = ("Assembly: stage 3 — always-on skills ship as condensed "
                  "checklists (Checklist + Recall anchors, per §5.8) with "
                  "pointers to the full skills; index use-when lines "
                  "truncated at a word boundary — full text in "
                  "`SKILLS_INDEX.md`.")
    budget = budget_for(ca_block)
    if budget >= 1:
        out = assemble(ca_block, budget)
        if tokens(out) < CORE_TOKEN_CAP:
            return out
    # Stage 4: always-on Rules+anchors+checklist, name/path-only index.
    STAGE_NOTE = ("Assembly: stage 4 — always-on skills condensed to Rules + "
                  "Recall anchors + Checklist; index lines carry name + path "
                  "only (use-when text lives in `SKILLS_INDEX.md`).")
    out = assemble(rca_block, 0)
    if tokens(out) < CORE_TOKEN_CAP:
        return out
    # Stage 5: condensed checklists + name/path-only index.
    STAGE_NOTE = ("Assembly: stage 5 — always-on skills ship as condensed "
                  "checklists (Checklist + Recall anchors, per §5.8); index "
                  "lines carry name + path only (use-when text lives in "
                  "`SKILLS_INDEX.md`).")
    return assemble(ca_block, 0)


def usage_counts(catalog):
    """How often each skill is named by other skills' Depends on / Feeds
    into metadata — the deterministic 'more-used' measure for rung-3
    splits. Counts mentions across the whole catalog, excluding self.
    """
    counts = {name: 0 for name in catalog}
    link_lines = {}
    for name, s in catalog.items():
        meta = section(s.text, "## Metadata")
        link_lines[name] = "\n".join(
            line for line in meta.splitlines()
            if line.startswith("- **Depends on:**")
            or line.startswith("- **Feeds into:**"))
    for name in catalog:
        pat = re.compile(r"(?<![a-z0-9\-])" + re.escape(name) + r"(?![a-z0-9\-])")
        counts[name] = sum(
            len(pat.findall(lines))
            for other, lines in link_lines.items() if other != name)
    return counts


def build_department(folder, dnum, skills, usage=None):
    """Return [(filename, text)] — one file, or two for a rung-3 split."""
    stamp = (f"<!-- generated by scripts/build-bundles.py on {gen_stamp()} — "
             "do not hand-edit; regenerate after any skill change -->")
    parts = [
        f"# Bundle: {folder}.md — {dnum} ({len(skills)} skills, bundle form)",
        "",
        stamp,
        "",
        "Bundle form: every skill of this department with its Metadata, "
        "When to use / Do NOT use, Rules, BAN list, Gates, Recall anchors, "
        "and Checklist in full. BAN entries keep ID, pattern, Defeats, "
        "Instead, and Severity; only the \"Bad:\" narrative example is "
        "omitted from this copy. The Examples and Anti-patterns sections "
        "and the BAN bad-examples live in the source skills — "
        f"`skills/{folder}/<skill>/SKILL.md` — and the full text of every "
        "skill is also in `bundles/ALL_SKILLS.md`. Load only the "
        "departments a task needs (BOOTSTRAP.md § routing).",
        "",
    ]
    for s in skills:
        parts += ["---", "", s.bundle_form(), ""]
    rung1 = "\n".join(parts)
    if tokens(rung1) <= BUNDLE_TOKEN_CAP:
        return [(f"{folder}.md", rung1)]

    # Rung 2: this department's bundle form still exceeds the cap.
    parts = [
        f"# Bundle: {folder}.md — {dnum} ({len(skills)} skills, "
        "bundle form, rung 2)",
        "",
        stamp,
        "",
        "Condensation rung 2: this bundle is additionally condensed "
        "because bundle form alone exceeded the 30,000-token cap for this "
        "department. As in bundle form, every skill ships with its When "
        "to use / Do NOT use, Rules, BAN list (ID, pattern, Defeats, "
        "Instead, Severity; the \"Bad:\" narrative is omitted), Gates, "
        "and Checklist, and the Examples and Anti-patterns sections are "
        "not copied. Rung 2 additionally omits each skill's Recall "
        "anchors section and Metadata Sources line, and condenses each "
        "gate's Check to its first sentence — Pass criteria and Fail "
        "actions are complete and exact. Everything omitted or condensed "
        "here lives in full in the source skills — "
        f"`skills/{folder}/<skill>/SKILL.md` — and in "
        "`bundles/ALL_SKILLS.md`. Load only the departments a task needs "
        "(BOOTSTRAP.md § routing).",
        "",
    ]
    for s in skills:
        parts += ["---", "", s.bundle_form_rung2(), ""]
    rung2 = "\n".join(parts)
    if tokens(rung2) <= BUNDLE_TOKEN_CAP:
        return [(f"{folder}.md", rung2)]

    # Rung 3: also omit each skill's Checklist section (every item
    # restates a rule kept in full). Rules/BAN substance never condensed.
    rung3_note = (
        "Condensation rung 3: this bundle is additionally condensed "
        "because rung 2 still exceeded the 30,000-token cap for this "
        "department. As in bundle form, every skill ships with its When "
        "to use / Do NOT use, Rules, and BAN list (ID, pattern, Defeats, "
        "Instead, Severity; the \"Bad:\" narrative is omitted), and the "
        "Examples and Anti-patterns sections are not copied. Rung 2 "
        "additionally omits each skill's Recall anchors section and "
        "Metadata Sources line, and condenses each gate's Check to its "
        "first sentence — Pass criteria and Fail actions are complete "
        "and exact. Rung 3 additionally omits each skill's Checklist "
        "section — every checklist item restates a rule that remains in "
        "full in this bundle, and the checklists live in the source "
        f"skills — `skills/{folder}/<skill>/SKILL.md`. Everything "
        "omitted or condensed here lives in full in the source skills "
        "and in `bundles/ALL_SKILLS.md`. Load only the departments a "
        "task needs (BOOTSTRAP.md § routing).")
    parts = [
        f"# Bundle: {folder}.md — {dnum} ({len(skills)} skills, "
        "bundle form, rung 3)",
        "",
        stamp,
        "",
        rung3_note,
        "",
    ]
    for s in skills:
        parts += ["---", "", s.bundle_form_rung3(), ""]
    rung3 = "\n".join(parts)
    if tokens(rung3) <= BUNDLE_TOKEN_CAP:
        return [(f"{folder}.md", rung3)]

    # Rung-3 split: still over cap — split at a skill boundary into two
    # rung-3 files, more-used skills (by catalog-wide Depends on / Feeds
    # into mentions) in part 1. Each part's header names the other part
    # and lists which skills each part holds.
    if usage is None:
        usage = {}
    ordered_skills = sorted(
        skills, key=lambda s: (-usage.get(s.name, 0), s.name))
    rendered = {s.name: s.bundle_form_rung3() for s in ordered_skills}

    def part_text(part_no, mine, other):
        names = ", ".join(f"`{s.name}`" for s in mine)
        other_names = ", ".join(f"`{s.name}`" for s in other)
        other_file = f"{folder}-2.md" if part_no == 1 else f"{folder}.md"
        head = [
            f"# Bundle: {folder}.md — {dnum} ({len(skills)} skills, "
            f"bundle form, rung 3, split part {part_no} of 2)"
            if part_no == 1 else
            f"# Bundle: {folder}-2.md — {dnum} ({len(skills)} skills, "
            "bundle form, rung 3, split part 2 of 2)",
            "",
            stamp,
            "",
            f"Split bundle: this department ships in two parts because "
            f"one rung-3 file still exceeded the 30,000-token cap. This "
            f"is part {part_no} of 2; the other part is "
            f"`bundles/{other_file}`. Part 1 holds the department's "
            f"more-used skills; part 2 holds the rest. This part holds: "
            f"{names}. The other part holds: {other_names}.",
            "",
            rung3_note,
            "",
        ]
        body = []
        for s in mine:
            body += ["---", "", rendered[s.name], ""]
        return "\n".join(head + body)

    part1, part2 = [], list(ordered_skills)
    for s in ordered_skills:
        trial = part1 + [s]
        rest = [x for x in part2 if x is not s]
        if tokens(part_text(1, trial, rest)) <= BUNDLE_TOKEN_CAP:
            part1, part2 = trial, rest
    return [(f"{folder}.md", part_text(1, part1, part2)),
            (f"{folder}-2.md", part_text(2, part2, part1))]


def build_playbook(slug, catalog, gindex):
    pb_path = PLAYBOOKS_DIR / f"{slug}.md"
    pb_text = pb_path.read_text(encoding="utf-8").rstrip()
    names, _missing = parse_playbook_skills(pb_text, catalog)
    keys = [n for n in KEY_SKILLS.get(slug, []) if n in names]
    work = [n for n in names if n not in ALWAYS_ON]
    rest = [n for n in work if n not in keys]
    digest = gate_digest(pb_text, work, catalog, gindex)

    def assemble(rung):
        if rung == 1:
            render = {n: catalog[n].full() for n in keys}
            render.update({n: catalog[n].condensed(
                ["## Rules", "## Checklist"], "Rules + Checklist") for n in rest})
            classes = (f"{len(keys)} key skills in full, {len(rest)} condensed "
                       "to Rules + Checklist")
        elif rung == 2:
            render = {n: catalog[n].condensed(
                ["## Rules", "## Checklist"], "Rules + Checklist") for n in work}
            classes = f"all {len(work)} skills condensed to Rules + Checklist"
        elif rung == 3:
            render = {n: catalog[n].condensed(
                ["## Rules", "## Checklist"], "Rules + Checklist") for n in keys}
            render.update({n: catalog[n].pointer() for n in rest})
            classes = (f"{len(keys)} key skills condensed to Rules + Checklist, "
                       f"{len(rest)} as pointers")
        else:
            render = {n: catalog[n].pointer() for n in work}
            classes = f"all {len(work)} skills as pointers"
        key_note = (", ".join(f"`{n}`" for n in keys) if keys else
                    "none — this playbook has no §5.6 key-skill list "
                    "(added by DECISIONS D-007)")
        parts = [
            f"# Bundle: {slug}.md — playbook + its skills",
            "",
            f"<!-- generated by scripts/build-bundles.py on {gen_stamp()} — "
            "do not hand-edit; regenerate after any skill or playbook change -->",
            "",
            f"Assembly rung {rung}: {classes}. Key skills (§5.6): {key_note}. "
            "Condensed and pointer entries point at the full skill; full text "
            "also lives in the department bundles. The four always-on core "
            "skills (step 0) are NOT repeated here — they ship in "
            "`bundles/core.md`, which this playbook loads first. Every rung "
            "ends with the gate criteria digest: each gate this playbook "
            "cites, with its check criterion and its Pass criterion complete, "
            "from the owning skill — this bundle is the default complete "
            "load for the walk (BOOTSTRAP.md step 3).",
            "",
            f"<!-- generated from playbooks/{slug}.md -->",
            "",
            pb_text,
            "",
            "---",
            "",
            "## Skills for this playbook (in playbook order)",
            "",
        ]
        for n in work:
            parts += [render[n], ""]
        if digest:
            parts += ["---", "", digest, ""]
        return "\n".join(parts)

    for rung in (1, 2, 3, 4):
        out = assemble(rung)
        if tokens(out) <= BUNDLE_TOKEN_CAP:
            return out
    return out  # rung 4 is minimal; if it still exceeds, the table reports FAIL


def build_all_skills(ordered):
    parts = [
        "# ALL_SKILLS.md — every skill in one file (reference only)",
        "",
        "DO NOT LOAD WHOLE — use bundles/ or SKILLS_INDEX.md.",
        "",
        f"<!-- generated by scripts/build-bundles.py on {gen_stamp()} — "
        "do not hand-edit; regenerate after any skill change -->",
        "",
        "The full text of every skill in the catalog, in department order "
        "(D1–D18), for offline search and download. Examples/ files are not "
        "included; they live in each skill's folder.",
        "",
    ]
    for dnum, folder, skills in ordered:
        parts += [f"## Department {dnum} — {folder}", ""]
        for s in skills:
            parts += ["---", "", s.full(), ""]
    return "\n".join(parts)


def main():
    catalog, ordered = load_catalog()
    errors = []

    # Validate every reference before writing anything (§5.8 generation rule).
    for name in ALWAYS_ON:
        if name not in catalog:
            errors.append(f"always-on skill missing: {name}")
    playbook_texts = {}
    for slug in KEY_SKILLS:
        pb = PLAYBOOKS_DIR / f"{slug}.md"
        if not pb.exists():
            errors.append(f"playbook missing: playbooks/{slug}.md")
            continue
        text = pb.read_text(encoding="utf-8")
        playbook_texts[slug] = text
        _names, missing = parse_playbook_skills(text, catalog)
        for m in missing:
            errors.append(f"playbooks/{slug}.md references missing skill: {m}")
    for s in catalog.values():
        if s.lines > SKILL_LINE_CAP:
            errors.append(f"{s.rel}: {s.lines} lines > {SKILL_LINE_CAP} line cap")
    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        return 1

    BUNDLES_DIR.mkdir(exist_ok=True)
    results = []  # (filename, tokens, cap or None, status)

    stamp_re = re.compile(r"on \d{4}-\d{2}-\d{2} \d{2}:\d{2} UTC")

    def emit(filename, text, cap, strict_under=False):
        path = BUNDLES_DIR / filename
        if path.exists():
            old = path.read_text(encoding="utf-8")
            if stamp_re.sub("on <stamp>", old) == stamp_re.sub("on <stamp>", text):
                text = old  # unchanged apart from the stamp: keep the file
        path.write_text(text, encoding="utf-8")
        t = tokens(text)
        if cap is None:
            status = "n/a (reference)"
        else:
            ok = t < cap if strict_under else t <= cap
            status = "PASS" if ok else "FAIL"
        results.append((filename, t, cap, status))

    emit("core.md", build_core(catalog, ordered), CORE_TOKEN_CAP, strict_under=True)
    usage = usage_counts(catalog)
    produced = set()
    for dnum, folder, skills in ordered:
        for filename, text in build_department(folder, dnum, skills, usage):
            emit(filename, text, BUNDLE_TOKEN_CAP)
            produced.add(filename)
    # Remove stale split parts from earlier runs (a department that no
    # longer splits must not leave its <folder>-2.md behind).
    for _dnum, folder, _skills in ordered:
        stale = BUNDLES_DIR / f"{folder}-2.md"
        if stale.exists() and stale.name not in produced:
            stale.unlink()
    gindex = gate_index(catalog)
    for slug in KEY_SKILLS:
        emit(f"{slug}.md", build_playbook(slug, catalog, gindex),
             BUNDLE_TOKEN_CAP)
    emit("ALL_SKILLS.md", build_all_skills(ordered), None)

    width = max(len(r[0]) for r in results)
    print(f"{'bundle':<{width}}  {'tokens':>8}  {'cap':>8}  status")
    failures = 0
    for filename, t, cap, status in results:
        cap_s = f"{cap:,}" if cap else "—"
        print(f"{filename:<{width}}  {t:>8,}  {cap_s:>8}  {status}")
        if status == "FAIL":
            failures += 1
    print(f"\n{len(results)} bundles written to bundles/. "
          f"{failures} cap failure(s).")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
