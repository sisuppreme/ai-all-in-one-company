#!/usr/bin/env python3
"""Reference project generator -- serves rule PM-006 and gate G-PM-001
(project-templates skill, D10).

Emits exactly the file set listed in a project type's shipped manifest,
`templates/mandated-manifest-<type>.txt` -- the manifest is the
normative artifact; where this generator's output and the manifest
disagree, the manifest governs and the generator is fixed (PM-006).

    python3 scripts/generate-project.py --type landing-page \
        --target /path/to/new-project

What each emitted file contains:

- Where `templates/` carries a file with the manifest entry's name
  (today: `.markdownlint.json`, the starter lint configuration of
  DECISIONS D-017), that file is copied verbatim.
- Every other entry is an honest empty-section scaffold: structure
  only, no project content, no invented names, metrics, or dates
  (PM-002, PM-003, PM-004). Markdown files get their title heading
  and a provenance comment; requirements.md additionally gets the
  four sections BOOTSTRAP step 4 prescribes (Goal, Audience, Key
  features, Acceptance criteria), and SECURITY.md the two named
  sections PM-010 prescribes (Reporting a vulnerability, Security
  design). Scaffolds contain no substitution tokens and no draft
  markers, so the generated tree passes G-PM-002 as emitted.
- Files that already exist in the target are left untouched and
  reported as present.

After emitting, the generator diffs the target tree against the
manifest (the G-PM-001 check) and prints the result.

Exit codes: 0 = manifest diff clean; 1 = diff not clean (missing or
extra files, listed); 2 = setup error (unknown type, bad target).
Standard library only.
"""

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = REPO_ROOT / "templates"

PROVENANCE = ("Starter scaffold generated by scripts/generate-project.py "
              "from templates/mandated-manifest-{type}.txt -- structure "
              "only; no project content yet.")
ACRONYMS = {"API", "ADR"}


def fail_setup(msg):
    print(f"generate-project: setup error: {msg}", file=sys.stderr)
    sys.exit(2)


def available_types():
    return sorted(p.name[len("mandated-manifest-"):-len(".txt")]
                  for p in TEMPLATES.glob("mandated-manifest-*.txt"))


def title_for(rel):
    stem = Path(rel).stem
    words = []
    for w in stem.replace("-", "_").split("_"):
        if not w:
            continue
        words.append(w.upper() if w.upper() in ACRONYMS
                     else w.capitalize())
    return " ".join(words) or "Untitled"


def scaffold(rel, ptype):
    """Honest empty-section scaffold for one manifest entry."""
    name = Path(rel).name
    if name == ".gitkeep":
        return ""
    if name == ".env.example":
        return ("# Environment variables -- names only; values live "
                "in the secret store\n# (see the secrets-management "
                "skill). No variables declared yet.\n")
    if name == ".gitignore":
        return ("# Generated by scripts/generate-project.py\n"
                ".env\nnode_modules/\ndist/\n__pycache__/\n.scratch/\n")
    if name == "dependabot.yml":
        return ("# Dependabot configuration -- no update rules "
                "configured yet.\nversion: 2\nupdates: []\n")
    if name == "CODEOWNERS":
        return ("# Code owners -- none assigned yet.\n"
                "# Add one line per path: <path> <owner>\n")
    if name == "LICENSE":
        return ("LICENSE -- starter scaffold generated by "
                "scripts/generate-project.py.\n\nNo license has been "
                "chosen for this project yet; this file intentionally "
                "contains\nno license text. Record the choice in "
                "DECISIONS.md and replace this file with\nthe license "
                "text before any public release.\n")
    if rel.endswith(".md"):
        lines = [f"# {title_for(rel)}", "",
                 f"<!-- {PROVENANCE.format(type=ptype)} -->", ""]
        if name == "requirements.md":
            lines += ["## Goal", "", "## Audience", "",
                      "## Key features", "", "## Acceptance criteria",
                      ""]
        elif name == "SECURITY.md":
            lines += ["## Reporting a vulnerability", "",
                      "## Security design", ""]
        return "\n".join(lines)
    if rel.endswith((".yml", ".yaml")):
        return ("# Starter scaffold generated by "
                "scripts/generate-project.py -- not yet configured.\n")
    return ("Starter scaffold generated by "
            "scripts/generate-project.py -- no content yet.\n")


def main():
    ap = argparse.ArgumentParser(
        description="Generate a fresh project emitting exactly the "
                    "file set of templates/mandated-manifest-<type>"
                    ".txt (PM-006), then print the G-PM-001 manifest "
                    "diff. See the module docstring for what each "
                    "emitted file contains.")
    ap.add_argument("--type", required=True,
                    help="project type (a shipped manifest name, e.g. "
                         "landing-page, saas-web-app)")
    ap.add_argument("--target", required=True,
                    help="directory to generate into (created if "
                         "missing; existing files are left untouched)")
    args = ap.parse_args()

    types = available_types()
    if args.type not in types:
        fail_setup(f"unknown project type {args.type!r}; shipped "
                   f"manifests: {', '.join(types)}")
    manifest_path = TEMPLATES / f"mandated-manifest-{args.type}.txt"
    entries = [line.strip() for line in
               manifest_path.read_text(encoding="utf-8").splitlines()
               if line.strip()]

    target = Path(args.target)
    if target.exists() and not target.is_dir():
        fail_setup(f"target is not a directory: {target}")
    target.mkdir(parents=True, exist_ok=True)

    created, present, copied = [], [], []
    for entry in entries:
        rel = entry[2:] if entry.startswith("./") else entry
        dest = target / rel
        if dest.exists():
            present.append(entry)
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        template = TEMPLATES / Path(rel).name
        if template.is_file():
            dest.write_text(template.read_text(encoding="utf-8"),
                            encoding="utf-8")
            copied.append(entry)
        else:
            dest.write_text(scaffold(rel, args.type),
                            encoding="utf-8")
            created.append(entry)

    actual = {"./" + p.relative_to(target).as_posix()
              for p in target.rglob("*") if p.is_file()}
    wanted = set(entries)
    missing = sorted(wanted - actual)
    extra = sorted(actual - wanted)
    print(f"generate-project: type {args.type}: {len(created)} "
          f"scaffold(s) created, {len(copied)} template file(s) "
          f"copied, {len(present)} already present")
    if missing or extra:
        print(f"generate-project: manifest diff: NOT clean "
              f"({len(missing)} missing, {len(extra)} extra)")
        for e in missing:
            print(f"  missing: {e}")
        for e in extra:
            print(f"  extra:   {e}")
        return 1
    print(f"generate-project: manifest diff: clean -- {len(wanted)}/"
          f"{len(wanted)} files present, 0 missing, 0 extra "
          f"(G-PM-001)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
